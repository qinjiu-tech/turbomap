/** 按序号生成一个点。index 对城市数取模；分布由序号决定，刷新不会换一套点。 */
export function pointAt(index: number): MapPoint {
  // 取模分配锚点，点数少于城市数时也能从东到西都有代表。
  const [name, longitude, latitude] = CITY_ANCHORS[index % CITY_ANCHORS.length]
  // 种子用序号。每次十万点的分布都一样，方便对照。
  const random = mulberry32(index + 1)
  const angle = random() * Math.PI * 2
  // 半径用平方根展开，点在圆盘里更均匀，而不是堆在圆心。
  const radius = Math.sqrt(random()) * 1.15
  // 纬度直接加减半径。经度还要再除以余弦，两轴的地面距离才接近。
  const nextLatitude = latitude + Math.sin(angle) * radius
  return {
    id: `${name} · ${index + 1}`,
    position: {
      // 经度按纬度余弦拉开，避免高纬度的点在东西方向挤成一团。
      longitude: longitude + (Math.cos(angle) * radius) / Math.cos((nextLatitude * Math.PI) / 180),
      latitude: nextLatitude,
    },
  }
}

/** 把序号映射成稳定随机。不用 Math.random，否则每次刷新点的位置都会变。 */
function mulberry32(seed: number): () => number {
  // 把序号映射成稳定随机，方便对照同一次数据。
  let state = seed
  return () => {
    state += 0x6d2b79f5
    let value = state
    value = Math.imul(value ^ (value >>> 15), value | 1)
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61)
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296
  }
}
